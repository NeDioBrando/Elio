#!/usr/bin/env python3
"""Emit the shipping artifacts from a verified manifest.

    SoundBank.luau  data only, one entry per role   -> src/shared/Config/
    Sfx.luau        the runtime helper              -> src/shared/
    install.lua     builds the Sounds in the place  -> execute_luau

The bank is DATA and the helper is CODE, which is the same split every other
tunable in a well-structured game project uses. Nothing downstream is allowed to
hardcode an asset id.

install.lua exists so a place with no Rojo sync can still hear the result. It
is not the shipping path; the module pair is.

    emit_bank.py work/manifest.json --out work/
"""

from __future__ import annotations

import argparse
import json
from pathlib import Path

BANK_HEAD = """--!strict
-- SoundBank: every sound this game uses, by role.
--
-- GENERATED by the roblox-sfx skill from a manifest whose every entry was
-- loaded and measured in Studio. Do not hand-edit: re-run the skill.
--
-- Every id below is a free Roblox Creator Store asset used BY ID. Nothing was
-- uploaded, so none of this touches the Open Cloud audio quota.
--
-- `length` is Sound.TimeLength as measured in Studio, never the toolbox
-- listing's duration field, which is wrong often enough to be dangerous.

export type Entry = {
\tid: number,
\tlength: number,
\tvolume: number,
\tlooped: boolean,
\tname: string,
\tcreator: string,
}

local SoundBank: { [string]: Entry } = {
"""

BANK_TAIL = """}

return SoundBank
"""

SFX = '''--!strict
-- Sfx: play a sound by ROLE, never by id.
--
-- Standing rule: cosmetics can never break gameplay. Every entry point here is
-- pcall-isolated and fails inert - a missing sound must never stop a shot from
-- firing or a sheep from moving.

local ContentProvider = game:GetService("ContentProvider")
local Debris = game:GetService("Debris")
local SoundService = game:GetService("SoundService")

local SoundBank = require(script.Parent.Config.SoundBank)

local Sfx = {}

local TEMPLATES = "SfxTemplates"
local TAIL = 0.5 -- grace after TimeLength before the clone is destroyed

local function templates(): Folder
\tlocal folder = SoundService:FindFirstChild(TEMPLATES)
\tif not folder then
\t\tfolder = Instance.new("Folder")
\t\tfolder.Name = TEMPLATES
\t\tfolder.Parent = SoundService
\tend
\treturn folder :: Folder
end

local function template(role: string): Sound?
\tlocal entry = SoundBank[role]
\tif not entry then
\t\twarn(`[Sfx] no such role: {role}`)
\t\treturn nil
\tend
\tlocal folder = templates()
\tlocal existing = folder:FindFirstChild(role)
\tif existing and existing:IsA("Sound") then
\t\treturn existing
\tend
\tlocal sound = Instance.new("Sound")
\tsound.Name = role
\tsound.SoundId = `rbxassetid://{entry.id}`
\tsound.Volume = entry.volume
\tsound.Looped = entry.looped
\tsound.Parent = folder
\treturn sound
end

--- Warm every asset. Yields, so call it from a spawned thread at startup.
function Sfx.preload()
\tlocal list = {}
\tfor role in SoundBank do
\t\tlocal t = template(role)
\t\tif t then
\t\t\ttable.insert(list, t)
\t\tend
\tend
\tpcall(function()
\t\tContentProvider:PreloadAsync(list)
\tend)
end

--- Play `role`. `parent` may be a BasePart or Attachment for 3D sound, or nil
--- for a flat 2D sound. `pitchVary` is a half-range, so 0.1 gives 0.9x - 1.1x.
--- Returns the playing Sound, or nil if anything at all went wrong.
function Sfx.play(role: string, parent: Instance?, pitchVary: number?): Sound?
\tlocal ok, result = pcall(function(): Sound?
\t\tlocal source = template(role)
\t\tif not source then
\t\t\treturn nil
\t\tend
\t\tlocal entry = SoundBank[role]
\t\tlocal clone = source:Clone()
\t\tif pitchVary and pitchVary > 0 then
\t\t\tclone.PlaybackSpeed = 1 + (math.random() * 2 - 1) * pitchVary
\t\tend
\t\tclone.Parent = parent or SoundService
\t\tclone:Play()
\t\tif not entry.looped then
\t\t\t-- PlaybackSpeed stretches real time, so scale the lifetime by it.
\t\t\tDebris:AddItem(clone, entry.length / math.max(clone.PlaybackSpeed, 0.01) + TAIL)
\t\tend
\t\treturn clone
\tend)
\tif not ok then
\t\twarn(`[Sfx] {role} failed inert: {result}`)
\t\treturn nil
\tend
\treturn result
end

--- Stop a looping sound started with Sfx.play.
function Sfx.stop(sound: Sound?)
\tif sound then
\t\tpcall(function()
\t\t\tsound:Stop()
\t\t\tsound:Destroy()
\t\tend)
\tend
end

return Sfx
'''

INSTALL_HEAD = """-- roblox-sfx: build the verified sounds straight into this place.
-- Generated. Creates SoundService/SFX/<role>, ready to hear immediately.
local SoundService = game:GetService("SoundService")

local root = SoundService:FindFirstChild("SFX")
if not root then
\troot = Instance.new("Folder")
\troot.Name = "SFX"
\troot.Parent = SoundService
end
root:ClearAllChildren()

local BANK = {
"""

INSTALL_TAIL = """}

for _, e in ipairs(BANK) do
\tlocal s = Instance.new("Sound")
\ts.Name = e.role
\ts.SoundId = "rbxassetid://" .. tostring(e.id)
\ts.Volume = e.volume
\ts.Looped = e.looped
\ts.Parent = root
end

return string.format("installed %d sounds under SoundService.SFX", #BANK)
"""


TOUR_HEAD = """-- roblox-sfx: play the whole bank out loud, spaced by each sound's real length.
-- Generated. Studio plays Sounds in edit mode, so this needs no playtest.
-- Returns immediately and schedules the rest with task.delay, because
-- execute_luau drops its output if the script yields.
local SoundService = game:GetService("SoundService")

local root = SoundService:FindFirstChild("SFX")
if not root then
\treturn "run install.lua first"
end

local TOUR = {
"""

TOUR_TAIL = """}

local GAP = 0.4
local at = 0
for _, e in ipairs(TOUR) do
\tlocal offset = at
\ttask.delay(offset, function()
\t\tlocal s = root:FindFirstChild(e.role)
\t\tif s and s:IsA("Sound") then
\t\t\ts.TimePosition = 0
\t\t\ts:Play()
\t\t\tprint(string.format("%5.1fs  %s", offset, e.role))
\t\tend
\tend)
\tat += e.length + GAP
end

return string.format("touring %d sounds over %.1f seconds - listen", #TOUR, at)
"""


def write_lf(path, text: str) -> None:
    """newline="" so Windows does not write CRLF. The .luau files here land in a
    repo whose stylua gate normalises to LF, and a CRLF file fails that gate as
    entirely unformatted."""
    with open(path, "w", encoding="utf-8", newline="") as fh:
        fh.write(text)


def lua_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("manifest")
    ap.add_argument("--out", default="work")
    ap.add_argument("--allow-holes", action="store_true",
                    help="emit even though roles are unfilled (you will ship a silent role)")
    a = ap.parse_args()

    m = json.loads(Path(a.manifest).read_text(encoding="utf-8"))
    if m.get("unfilled") and not a.allow_holes:
        names = ", ".join(u["role"] for u in m["unfilled"])
        raise SystemExit(f"refusing to emit: {len(m['unfilled'])} unfilled role(s): {names}\n"
                         f"fix the search or pass --allow-holes deliberately.")

    out = Path(a.out)
    out.mkdir(parents=True, exist_ok=True)

    rows = []
    inst = []
    tour = []
    for s in sorted(m["sounds"], key=lambda x: x["role"]):
        tour.append(f"\t{{ role = {lua_str(s['role'])}, length = {s['length']} }},")
        rows.append(
            f"\t[{lua_str(s['role'])}] = {{\n"
            f"\t\tid = {s['id']},\n"
            f"\t\tlength = {s['length']},\n"
            f"\t\tvolume = {s['volume']},\n"
            f"\t\tlooped = {str(s['looped']).lower()},\n"
            f"\t\tname = {lua_str(s['name'])},\n"
            f"\t\tcreator = {lua_str(s['creator'])},\n"
            f"\t}},"
        )
        inst.append(
            f"\t{{ role = {lua_str(s['role'])}, id = {s['id']}, "
            f"volume = {s['volume']}, looped = {str(s['looped']).lower()} }},"
        )

    write_lf(out / "SoundBank.luau", BANK_HEAD + "\n".join(rows) + "\n" + BANK_TAIL)
    write_lf(out / "Sfx.luau", SFX)
    write_lf(out / "install.lua", INSTALL_HEAD + "\n".join(inst) + "\n" + INSTALL_TAIL)
    write_lf(out / "tour.lua", TOUR_HEAD + "\n".join(tour) + "\n" + TOUR_TAIL)

    print(f"{out/'SoundBank.luau'}  {len(rows)} roles  -> src/shared/Config/")
    print(f"{out/'Sfx.luau'}                       -> src/shared/")
    print(f"{out/'install.lua'}      -> execute_luau, to hear it in this place now")
    print(f"{out/'tour.lua'}         -> execute_luau, plays the whole bank in order")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
