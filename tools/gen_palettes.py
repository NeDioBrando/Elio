"""Regenerates the Liquid Glass palette tokens inside core/theme.css (and its extension mirror).

Run:  python tools/gen_palettes.py
Every palette has a light and a dark variant. Text/background pairs are checked for WCAG AA (4.5:1)
and the accent lightness is nudged automatically until the checks pass, so adding a palette is just a
new row in PALETTES.
"""
import colorsys, json, re, shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEGIN = '/* PALETTES:BEGIN generated by tools/gen_palettes.py - do not edit by hand */'
END = '/* PALETTES:END */'

# id, display name, hue (deg), saturation (0..1), blob hues (a, b, c)
PALETTES = [
    ('aurora',   'Aurora',   172, 0.62, (172, 268, 205)),
    ('ocean',    'Ocean',    214, 0.70, (214, 188, 248)),
    ('amethyst', 'Amethyst', 266, 0.60, (266, 302, 232)),
    ('orchid',   'Orchid',   292, 0.52, (292, 330, 258)),
    ('sakura',   'Sakura',   336, 0.62, (336, 14, 298)),
    ('ember',    'Ember',     22, 0.74, (22, 46, 352)),
    ('crimson',  'Crimson',  352, 0.62, (352, 14, 322)),
    ('emerald',  'Emerald',  152, 0.55, (152, 118, 184)),
    ('graphite', 'Graphite', 220, 0.10, (220, 244, 198)),
]


def hsl(h, s, l):
    r, g, b = colorsys.hls_to_rgb((h % 360) / 360.0, max(0, min(1, l)), max(0, min(1, s)))
    return '#%02x%02x%02x' % (round(r * 255), round(g * 255), round(b * 255))


def lum(hexv):
    ch = [int(hexv[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    ch = [c / 12.92 if c <= .04045 else ((c + .055) / 1.055) ** 2.4 for c in ch]
    return ch[0] * .2126 + ch[1] * .7152 + ch[2] * .0722


def contrast(a, b):
    x, y = sorted((lum(a), lum(b)), reverse=True)
    return (x + .05) / (y + .05)


def light(h, s):
    t = dict(
        canvas=hsl(h, s * .38, .925), sidebar=hsl(h, s * .36, .885), surface=hsl(h, s * .42, .965),
        raised=hsl(h, s * .40, .905), line=hsl(h, s * .26, .70),
        text=hsl(h, min(.35, s * .6), .115), muted=hsl(h, min(.22, s * .35), .30), subtle=hsl(h, min(.2, s * .3), .32),
        selected=hsl(h, s * .55, .80), **{'on-accent': '#ffffff'})
    l = .40
    while True:
        acc = hsl(h, s, l)
        if contrast(acc, '#ffffff') >= 4.8 and contrast(acc, t['surface']) >= 4.5:
            break
        l -= .01
    t['accent'] = acc
    return t


def dark(h, s):
    t = dict(
        canvas=hsl(h, s * .50, .075), sidebar=hsl(h, s * .50, .055), surface=hsl(h, s * .42, .125),
        raised=hsl(h, s * .40, .17), line=hsl(h, s * .28, .30),
        text=hsl(h, min(.30, s * .5), .93), muted=hsl(h, min(.2, s * .3), .75), subtle=hsl(h, min(.2, s * .3), .70),
        selected=hsl(h, s * .50, .25))
    l = .70
    while True:
        acc = hsl(h, min(1, s * 1.15), l)
        if contrast(acc, t['surface']) >= 6.5:
            break
        l += .01
    t['accent'] = acc
    t['on-accent'] = hsl(h, .5, .08)
    return t


def checks(mode, t):
    pairs = [('text', 'canvas', 7), ('text', 'surface', 7), ('muted', 'surface', 4.5), ('muted', 'canvas', 4.5),
             ('subtle', 'surface', 4.5), ('on-accent', 'accent', 4.5), ('text', 'selected', 4.5), ('muted', 'raised', 4.5)]
    for a, b, need in pairs:
        c = contrast(t[a], t[b])
        assert c >= need, f'{mode}: {a}/{b} {c:.2f} < {need}'


def block(sel, t, extra=''):
    body = ';'.join(f'--elio-{k}:{v}' for k, v in t.items())
    return f'{sel}{{{body};{extra}}}'


def build():
    out = [BEGIN, '/* Palette = tokens + Liquid Glass blobs (--lg-a/b/c) + logo gradient (--lg-logo-1/2/3). */']
    sw = []
    for pid, name, h, s, (ha, hb, hc) in PALETTES:
        lt, dk = light(h, s), dark(h, s)
        sat = max(.25, min(.9, s + .18)) if s > .2 else .12
        blobs_l = [hsl(ha, sat, .72), hsl(hb, sat, .76), hsl(hc, sat, .80)]
        blobs_d = [hsl(ha, sat, .34), hsl(hb, sat, .28), hsl(hc, sat, .24)]
        # muted/subtle text may sit directly on the blobs (no glass behind): keep >= 4.6:1 against the worst one
        for key in ('muted', 'subtle'):
            l = .32
            while min(contrast(lt[key], b) for b in blobs_l) < 4.6 and l > .08:
                l -= .01
                lt[key] = hsl(h, min(.22, s * .35), l)
            l = .75
            while min(contrast(dk[key], b) for b in blobs_d) < 4.6 and l < .97:
                l += .01
                dk[key] = hsl(h, min(.2, s * .3), l)
        checks(pid + ' light', lt)
        checks(pid + ' dark', dk)
        extra_l = f'--lg-a:{hsl(ha, sat, .72)};--lg-b:{hsl(hb, sat, .76)};--lg-c:{hsl(hc, sat, .80)};--lg-logo-1:{hsl(ha, sat, .56)};--lg-logo-2:{hsl(hb, sat, .42)};--lg-logo-3:{hsl(hc, sat, .84)}'
        extra_d = f'--lg-a:{hsl(ha, sat, .34)};--lg-b:{hsl(hb, sat, .28)};--lg-c:{hsl(hc, sat, .24)};--lg-logo-1:{hsl(ha, sat, .58)};--lg-logo-2:{hsl(hb, sat, .38)};--lg-logo-3:{hsl(hc, sat, .80)}'
        out.append(block(f'html[data-elio-palette="{pid}"]', lt, extra_l))
        out.append(block(f'html[data-elio-palette="{pid}"][data-elio-mode=dark]', dk, extra_d))
        sw.append(f'[data-elio-swatch="{pid}"]{{--sw-a:{hsl(ha, max(.5, sat), .60)};--sw-b:{hsl(hb, max(.5, sat), .52)}}}')
    out.append('/* swatches in the palette pickers */')
    out.extend(sw)
    out.append(END)
    return '\n'.join(out)


def main():
    for rel in ('core/theme.css',):
        p = ROOT / rel
        text = p.read_text(encoding='utf-8')
        region = build()
        if BEGIN in text:
            text = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END), lambda m: region, text, flags=re.S)
        else:
            text = text.rstrip('\n') + '\n' + region + '\n'
        p.write_text(text, encoding='utf-8')
        shutil.copy2(p, ROOT / 'elio-Extension' / rel)
    ids = [{'id': p[0], 'name': p[1]} for p in PALETTES]
    print('palettes:', json.dumps(ids))


if __name__ == '__main__':
    main()
