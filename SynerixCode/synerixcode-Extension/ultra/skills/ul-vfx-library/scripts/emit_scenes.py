#!/usr/bin/env python3
"""Pack every composition into ONE installable ModuleScript, plus a controller.

`compose.py` builds a payload for authoring a single effect in edit mode. This
is the shipping counterpart: it inlines all the compositions and the (deduped)
recipes they reference into a `VFXScenes` ModuleScript, and emits a `VFXDemo`
LocalScript that binds one key and one on-screen button to each effect.

The recipes are deduped across compositions on purpose. Several compositions
composed separately come to hundreds of KB because they each re-inline the same
handful of recipes; shared, it is a fraction of that. `emit_luau.py`'s warning
still applies - do not inline a whole large library, only what is used.

    python emit_scenes.py --lib DIR --comps DIR_OF_COMPOSITIONS --out-dir work
"""
import argparse
import json
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
LUAU = HERE / "luau"
sys.path.insert(0, str(HERE))
import compose as C  # noqa: E402

# The buttons appear in file-name order. A composition may carry its own on-screen
# "title"; otherwise the file name is used ("my_effect" -> "My Effect"). The demo
# controller binds the first eight to the keys 1-8.


def expand(body: str) -> str:
    """Same `--#include` splice payload.py does, so the engine is shared."""
    out = []
    for line in body.splitlines():
        inc = line.strip()
        if inc.startswith("--#include "):
            out.append((LUAU / f"{inc.split()[1]}.lua").read_text(encoding="utf-8"))
        else:
            out.append(line)
    return "\n".join(out)


def codec_prelude() -> str:
    codec = (LUAU / "codec.lua").read_text(encoding="utf-8")
    return codec.replace("\nreturn VFX\n", "\n")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--lib", action="append", default=[])
    ap.add_argument("--comps", required=True,
                    help="folder of YOUR composition .json files (you author these)")
    ap.add_argument("--out-dir", default=str(HERE.parent / "work"))
    a = ap.parse_args()

    libs = [pathlib.Path(x) for x in a.lib] or [C.default_lib()]
    comps_dir = pathlib.Path(a.comps)
    out_dir = pathlib.Path(a.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    comps, recipes, titles, order = {}, {}, {}, []
    problems = []
    files = sorted(comps_dir.glob("*.json"))
    if not files:
        raise SystemExit(f"no composition .json files in {comps_dir}")
    for f in files:
        name = f.stem
        comp = json.loads(f.read_text(encoding="utf-8"))
        title = comp.get("title") or name.replace("_", " ").title()
        rec = C.resolve_recipes(comp, libs)
        problems += [f"{name}: {p}" for p in C.check(comp, rec)]
        recipes.update(rec)
        comp.pop("camera", None)   # the player owns the camera in game
        comp.pop("notes", None)
        comps[name] = comp
        titles[name] = title
        order.append(name)
    if problems:
        for p in problems:
            print(f"  FAIL {p}", file=sys.stderr)
        raise SystemExit(f"{len(problems)} problem(s)")

    data = {"comps": comps, "recipes": recipes, "titles": titles,
            "order": order, "tail": 4.5}
    blob = json.dumps(data, separators=(",", ":"))
    if "]==]" in blob:
        raise SystemExit("composition data contains ]==] and would break the long string")

    module = (
        "-- GENERATED by scripts/emit_scenes.py - do not hand-edit.\n"
        "-- Edit your composition .json files or scripts/luau/{engine,runtime}.lua and re-emit.\n"
        + codec_prelude()
        + f"\nlocal SCENE_DATA = [==[{blob}]==]\n\n"
        + expand((LUAU / "runtime.lua").read_text(encoding="utf-8"))
    )
    (out_dir / "VFXScenes.lua").write_text(module, encoding="utf-8")

    controller = (LUAU / "demo_controller.lua").read_text(encoding="utf-8")
    (out_dir / "VFXDemo.lua").write_text(controller, encoding="utf-8")

    layers = sum(len(r["layers"]) for r in recipes.values())
    print(f"{out_dir / 'VFXScenes.lua'}  {len(module):,} chars  "
          f"compositions={len(comps)} recipes={len(recipes)} layers={layers}")
    print(f"{out_dir / 'VFXDemo.lua'}  {len(controller):,} chars")


if __name__ == "__main__":
    main()
