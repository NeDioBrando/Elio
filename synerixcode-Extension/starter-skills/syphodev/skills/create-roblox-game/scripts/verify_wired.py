#!/usr/bin/env python3
"""Gate the HANDOFF. Is every generated asset actually IN the game?

    verify_wired.py                      # static pass, then emit the probe
    verify_wired.py --report work/wired_report.txt   # judge the probe's output

WHY THIS EXISTS. On 2026-08-31 a build shipped with three empty ImageLabels in
its HUD. Every earlier gate was green: the icons were generated, cut out, the
mockup PNG showed them, `validate.py --stage-gate` passed because the artifacts
were on disk, and the five contract label NAMES were confirmed present in the
emitted tree. None of that asks the only question that matters at handoff -
**does the running game use the thing, or is it still a placeholder?**

The mesh had the same shape: `CoinService` was cloning a Cylinder while a
finished, uploaded coin mesh sat unused, because nothing had created the
template it looked for.

Both defects are invisible to every check that looks at files. They are only
visible in the assembled tree, so that is where this looks.

TWO PASSES, because neither is sufficient alone:

  1. STATIC - the emitted .model.json files on disk. Catches a placeholder that
     was never resolved before it ever reaches Studio.
  2. LIVE - a Luau probe run in Studio via execute_luau. Catches everything the
     static pass cannot see: instances built by scripts, assets installed
     place-side, and anything Rojo silently failed to apply.

THE COUNTS ARE PART OF THE CHECK. A probe that inspects zero ImageLabels and
reports "no failures" is not a pass, it is a check that never ran - the same
failure as a grey-parts check that never found its target. So every expected
class is declared from game.json's live stages, and finding none of one is a
FAILURE with its own message.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path

# className -> (property that must be non-empty, human name)
CONTENT_PROPS = {
    "ImageLabel": ("Image", "image"),
    "ImageButton": ("Image", "image"),
    "MeshPart": ("MeshId", "mesh"),
    "SpecialMesh": ("MeshId", "mesh"),
    "Decal": ("Texture", "texture"),
    "Texture": ("Texture", "texture"),
    "Sound": ("SoundId", "sound"),
}

# stage in game.json -> (probe counter key, minimum, why it must exist)
STAGE_EXPECTS = {
    "ui": ("ScreenGui", 1, "the ui stage is live, so the game must contain a ScreenGui"),
    "meshes": ("MeshPart", 1, "the meshes stage is live, so a generated mesh must be in the tree"),
    "sfx": ("Sound", 1, "the sfx stage is live, so the sound bank must be installed"),
}

PROBE = r'''-- Generated by verify_wired.py. Run in EDIT MODE via execute_luau.
-- Answers one question: is anything in this game still a placeholder?
local SERVICES = {
    game:GetService("Workspace"),
    game:GetService("ReplicatedStorage"),
    game:GetService("ServerScriptService"),
    game:GetService("ServerStorage"),
    game:GetService("StarterGui"),
    game:GetService("StarterPack"),
    game:GetService("StarterPlayer"),
    game:GetService("SoundService"),
    game:GetService("Lighting"),
}

local CONTENT = {
    ImageLabel = "Image", ImageButton = "Image",
    MeshPart = "MeshId", SpecialMesh = "MeshId",
    Decal = "Texture", Texture = "Texture",
    Sound = "SoundId",
}

-- Structural classes carry no content id, so the content loop never sees them -
-- and a stage expectation written against one would ask for a number that could
-- never exist. That is a FALSE FAILURE, which is worse than no check: the first
-- run of this script reported "found 0 ScreenGui" about a game that had one.
local STRUCTURE = { "ScreenGui", "ParticleEmitter", "Beam", "Trail", "Animation" }

-- Names the CONTRACT says must exist, injected by verify_wired.py from every
-- design/*.json that carries a `luau_contract` block.
--
-- This closes the cross-stage mismatch class. On 2026-08-31 HudController looked
-- up SoundService.CoinRoomSfx.coin_pickup while the sfx stage installed under
-- SoundService.SFX. Both ends fail INERT by design, so the HUD would have been
-- silently silent with every gate green and no error anywhere. A name that one
-- stage invents and another never agreed to is invisible to every other check.
local REQUIRED = { __REQUIRED__ }

local counts, empties, pending, deferred = {}, {}, {}, {}
local seen = {}

local function inspect(d)
    -- Record BOTH the bare name and the full dotted path.
    --
    -- REQUIRED holds contract entries like
    -- "ReplicatedStorage.Assets.Weapons.ExampleBlade", and this table used to be
    -- keyed only by d.Name ("ExampleBlade"). So the lookup below could never
    -- match, and every contract name reported MISSING no matter what the tree
    -- actually held - a check that cannot pass tells you nothing, and after the
    -- first run people stop reading it. Measured 2026-09-01 on a game whose
    -- eight contract instances were all present and correct.
    seen[d.Name] = true
    local okFull, full = pcall(function() return d:GetFullName() end)
    if okFull then
        seen[full] = true
    end
    for _, class in ipairs(STRUCTURE) do
        if d:IsA(class) then
            counts[class] = (counts[class] or 0) + 1
            break
        end
    end
    for class, prop in pairs(CONTENT) do
        if d:IsA(class) then
            counts[class] = (counts[class] or 0) + 1
            local ok, v = pcall(function() return d[prop] end)
            if ok and (v == nil or tostring(v) == "") then
                -- An empty content property is not automatically a defect. Some
                -- ids CANNOT ride in the instance file - Rojo 7.4.1 cannot sync
                -- an Image to current Studio at all - so they are carried as a
                -- named pointer and resolved by a controller at run time.
                --
                -- The distinction that matters is whether ANYTHING points at an
                -- id. "Empty, and a `Deferred` attribute naming a bank entry" is
                -- a design; "empty, with nothing pointing anywhere" is the blank
                -- HUD this whole check was written for. Report them separately
                -- and let the judge resolve the pointer against the bank.
                local okAttr, ptr = pcall(function() return d:GetAttribute("Icon") end)
                if okAttr and type(ptr) == "string" and ptr ~= "" then
                    table.insert(deferred, class .. "|" .. prop .. "|" .. d:GetFullName() .. "|" .. ptr)
                else
                    table.insert(empties, class .. "|" .. prop .. "|" .. d:GetFullName())
                end
            end
            break
        end
    end
    local ok, attrs = pcall(function() return d:GetAttributes() end)
    if ok and attrs then
        for k, av in pairs(attrs) do
            -- Same rule as the static pass: a Pending attribute with a VALUE is
            -- an unresolved placeholder, an empty one is the emitter having
            -- cleared it. Rojo cannot remove an attribute that vanishes from
            -- source, so "" is the only way to overwrite a stale value.
            if string.sub(k, 1, 7) == "Pending" and tostring(av) ~= "" then
                table.insert(pending, k .. "=" .. tostring(av) .. "|" .. d:GetFullName())
            end
        end
    end
end

for _, svc in ipairs(SERVICES) do
    local ok, kids = pcall(function() return svc:GetDescendants() end)
    if ok then
        for _, d in ipairs(kids) do
            inspect(d)
        end
    end
end

local lines = {}
for class, n in pairs(counts) do
    table.insert(lines, "COUNT " .. class .. " " .. n)
end
for _, e in ipairs(empties) do
    table.insert(lines, "EMPTY " .. e)
end
for _, p in ipairs(pending) do
    table.insert(lines, "PENDING " .. p)
end
for _, d in ipairs(deferred) do
    table.insert(lines, "DEFERRED " .. d)
end
for _, name in ipairs(REQUIRED) do
    if not seen[name] then
        table.insert(lines, "MISSING " .. name)
    end
end
table.insert(lines, "PROBE_OK")
return table.concat(lines, "\n")
'''


def contract_names(root: Path) -> list[str]:
    """Every instance name a design spec declares its code will look up.

    A `luau_contract` block is a stage saying "my code resolves these by name".
    Collecting them lets the live probe answer the one question no other check
    asks: does the name the code uses actually exist in the assembled tree?
    """
    names: list[str] = []
    for spec in sorted((root / "design").glob("*.json")):
        try:
            d = json.loads(spec.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            continue
        block = d.get("luau_contract")
        if not isinstance(block, dict):
            continue
        for key, val in block.items():
            if key.startswith("_") or key == "note":
                continue
            if isinstance(val, str):
                names.append(val)
            elif isinstance(val, dict):
                names.extend(k for k in val if not k.startswith("_"))
            elif isinstance(val, list):
                names.extend(str(v) for v in val)
    # stable and unique, so the probe payload does not churn between runs
    return sorted(set(n for n in names if n and " " not in n))


def walk_json(node, path=""):
    """Yield (className, name, props, attrs, path) for a Rojo .model.json tree."""
    if not isinstance(node, dict):
        return
    cls = node.get("className") or node.get("ClassName")
    name = node.get("name") or node.get("Name") or "?"
    here = f"{path}/{name}"
    if cls:
        yield cls, name, node.get("properties") or {}, node.get("attributes") or {}, here
    for child in node.get("children") or []:
        yield from walk_json(child, here)


def static_pass(root: Path) -> list[str]:
    problems: list[str] = []
    models = sorted(root.glob("assets/**/*.model.json"))
    if not models:
        problems.append(
            "no .model.json anywhere under assets/. If a stage emits instance "
            "files this check could not find them, which is a failure, not a pass."
        )
        return problems

    for m in models:
        try:
            tree = json.loads(m.read_text(encoding="utf-8"))
        except json.JSONDecodeError as exc:
            problems.append(f"{m.name} is not valid JSON: {exc}")
            continue
        rel = m.relative_to(root)
        for cls, _name, props, attrs, where in walk_json(tree):
            spec = CONTENT_PROPS.get(cls)
            if spec:
                prop, human = spec
                val = props.get(prop)
                if val is None or str(val).strip() == "":
                    problems.append(
                        f"{rel}: {where} is a {cls} with no {prop} - the {human} "
                        f"was never resolved to an asset id"
                    )
            for k, av in attrs.items():
                # A `Pending*` attribute means a placeholder. But an EMPTY one
                # means the opposite: the emitter actively clearing it.
                #
                # That distinction is forced by Rojo, not invented here. Rojo
                # restores a property without necessarily REMOVING an attribute
                # that no longer exists in source, so an emitter that simply
                # omits `PendingIcon` once the id is known leaves the previous
                # non-empty value sitting in Studio forever. Writing "" is the
                # only way to overwrite it. Failing on that would punish the
                # emitter for doing the correct thing, and the fix people would
                # reach for - omitting the attribute - reintroduces the exact
                # stale-value defect this check exists to catch.
                #
                # So: a NON-EMPTY Pending attribute is still a failure.
                if k.startswith("Pending") and str(av).strip() != "":
                    problems.append(
                        f"{rel}: {where} still carries the attribute {k!r} = {av!r} "
                        f"- that is the emitter saying it left a placeholder behind"
                    )
    return problems


def parse_report(text: str) -> tuple[dict[str, int], list[str], list[str], list[str], bool]:
    counts: dict[str, int] = {}
    empties: list[str] = []
    pending: list[str] = []
    deferred: list[str] = []
    ok = False
    for raw in text.splitlines():
        line = raw.strip().strip('"')
        line = line.replace("\\n", "")
        if line.startswith("COUNT "):
            parts = line.split()
            if len(parts) >= 3 and parts[2].isdigit():
                counts[parts[1]] = int(parts[2])
        elif line.startswith("EMPTY "):
            empties.append(line[6:])
        elif line.startswith("PENDING "):
            pending.append(line[8:])
        elif line.startswith("DEFERRED "):
            deferred.append(line[9:])
        elif line == "PROBE_OK":
            ok = True
    return counts, empties, pending, deferred, ok


def live_pass(root: Path, report: Path, live_stages: set[str]) -> list[str]:
    problems: list[str] = []
    text = report.read_text(encoding="utf-8")
    counts, empties, pending, deferred, ok = parse_report(text)

    if not ok:
        problems.append(
            f"{report.name} has no PROBE_OK line. The probe did not finish, so "
            f"this is UNVERIFIABLE - which is a failure result, not a pass."
        )
        return problems

    for e in empties:
        cls, prop, where = (e.split("|", 2) + ["?", "?"])[:3]
        problems.append(f"LIVE: {where} is a {cls} with an empty {prop}")
    for p in pending:
        attr, where = (p.split("|", 1) + ["?"])[:2]
        problems.append(f"LIVE: {where} still carries the placeholder attribute {attr!r}")

    # A DEFERRED id is only acceptable if the thing it points at actually
    # exists. Otherwise it is a blank with a note attached, which is worse than
    # a plain blank because it looks handled.
    if deferred:
        banks = "\n".join(
            b.read_text(encoding="utf-8", errors="ignore")
            for b in root.glob("src/shared/Config/*Bank.luau")
        )
        for d in deferred:
            _cls, prop, where, ptr = (d.split("|", 3) + ["?", "?", "?"])[:4]
            if not banks:
                problems.append(
                    f"LIVE: {where} defers its {prop} to {ptr!r}, but there is no "
                    f"*Bank.luau under src/shared/Config to resolve it against"
                )
            elif not re.search(rf"{re.escape(ptr)}\s*=", banks):
                problems.append(
                    f"LIVE: {where} defers its {prop} to {ptr!r}, which no bank "
                    f"defines - it will resolve to nothing and ship blank"
                )
            else:
                print(f"  deferred  {where}.{prop} -> {ptr} (resolved at runtime, in a bank)")
    for line in text.splitlines():
        line = line.strip().strip('"').replace("\n", "")
        if line.startswith("MISSING "):
            problems.append(
                f"LIVE: the contract declares {line[8:]!r} but no instance with that "
                f"name exists. Code resolving it by name will fail INERT - silently.")

    # The counts ARE the check. Zero of an expected class means the probe never
    # found its target, which reads identically to a clean pass and is not one.
    for stage, (cls, minimum, why) in STAGE_EXPECTS.items():
        if stage not in live_stages:
            continue
        got = counts.get(cls, 0)
        if got < minimum:
            problems.append(
                f"LIVE: found {got} {cls} in the whole game, expected at least "
                f"{minimum} - {why}"
            )
    return problems


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--dir", default=".")
    ap.add_argument("--report", default=None,
                    help="the probe's returned text, saved VERBATIM. Without it "
                         "this runs the static pass and writes the probe.")
    a = ap.parse_args()

    root = Path(a.dir).expanduser().resolve()
    game_path = root / "design" / "game.json"
    if not game_path.exists():
        raise SystemExit(f"no design/game.json under {root}")
    game = json.loads(game_path.read_text(encoding="utf-8"))
    live_stages = {
        n for n, c in (game.get("stages") or {}).items()
        if isinstance(c, dict) and c.get("status") != "skip"
    }

    problems = static_pass(root)
    header = f"wiring check: {game.get('title', '?')}   live stages: {', '.join(sorted(live_stages))}"
    print(header)
    print("-" * len(header))

    if a.report:
        rp = Path(a.report).expanduser()
        if not rp.exists():
            raise SystemExit(f"{rp} does not exist - run the probe and save its return verbatim")
        problems += live_pass(root, rp, live_stages)
        print("  static pass + LIVE pass")
    else:
        names = contract_names(root)
        payload = ", ".join(f'"{n}"' for n in names)
        probe = root / "work" / "wired_probe.lua"
        probe.parent.mkdir(parents=True, exist_ok=True)
        probe.write_text(PROBE.replace("__REQUIRED__", payload), encoding="utf-8")
        if names:
            print(f"  {len(names)} contract name(s) will be checked live: {', '.join(names)}")
        else:
            print("  NOTE: no design spec declares a `luau_contract`, so the live pass")
            print("  cannot check cross-stage names. Any name your code resolves at")
            print("  runtime should be declared there - that is the class of defect")
            print("  where both ends fail inert and every other gate stays green.")
        print("  static pass only")
        print(f"\n  NEXT, and it is not optional: run {probe.relative_to(root)} in EDIT MODE")
        print("  via execute_luau, save the returned text verbatim, then re-run:")
        print(f"    verify_wired.py --dir {root} --report work/wired_report.txt")
        print("  The static pass cannot see script-built instances or anything")
        print("  installed place-side, which is where both 2026-08-31 defects lived.")

    if problems:
        print(f"\n{len(problems)} problem(s):")
        for p in problems:
            print(f"  FAIL  {p}")
        print("\nNOT READY TO HAND OVER. Something generated is not in the game.")
        return 1

    if a.report:
        print("\nevery asset in the shipped tree resolves to a real id, and every")
        print("live stage is represented. Ready to hand over.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
