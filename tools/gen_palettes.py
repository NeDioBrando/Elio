"""Regenerates the palette tokens inside core/theme.css (and its extension mirror).

Run:  python tools/gen_palettes.py
Every palette has a light and a dark variant. Surfaces stay near-neutral (a faint tint of the palette
hue); only the accent carries the colour. Text/background pairs are checked for WCAG AA (4.5:1) and the
accent lightness is nudged automatically until the checks pass, so adding a palette is just a new row in
PALETTES.
"""
import colorsys, json, re, shutil
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
BEGIN = '/* PALETTES:BEGIN generated by tools/gen_palettes.py - do not edit by hand */'
END = '/* PALETTES:END */'

# id, display name, hue (deg), saturation (0..1), legacy blob hues (unused by the flat look)
PALETTES = [
    ('aurora',   'Aurora',   172, 0.62, (172, 268, 205)),
    ('ocean',    'Ocean',    214, 0.70, (214, 188, 248)),
    ('amethyst', 'Amethyst', 266, 0.60, (266, 302, 232)),
    ('orchid',   'Orchid',   292, 0.52, (292, 330, 258)),
    ('sakura',   'Sakura',   336, 0.62, (336, 14, 298)),
    ('ember',    'Ember',     22, 0.74, (22, 46, 352)),
    ('crimson',  'Crimson',  352, 0.62, (352, 14, 322)),
    ('emerald',  'Emerald',  152, 0.55, (152, 118, 184)),
    ('graphite', 'Graphite', 220, 0.10, (220, 244, 198)),
]


def hsl(h, s, l):
    r, g, b = colorsys.hls_to_rgb((h % 360) / 360.0, max(0, min(1, l)), max(0, min(1, s)))
    return '#%02x%02x%02x' % (round(r * 255), round(g * 255), round(b * 255))


def lum(hexv):
    ch = [int(hexv[i:i + 2], 16) / 255 for i in (1, 3, 5)]
    ch = [c / 12.92 if c <= .04045 else ((c + .055) / 1.055) ** 2.4 for c in ch]
    return ch[0] * .2126 + ch[1] * .7152 + ch[2] * .0722


def contrast(a, b):
    x, y = sorted((lum(a), lum(b)), reverse=True)
    return (x + .05) / (y + .05)


def light(h, s):
    tint = min(.10, s * .14)
    t = dict(
        canvas=hsl(h, tint, .965), sidebar=hsl(h, tint, .945), surface='#ffffff',
        raised=hsl(h, tint, .945), line=hsl(h, tint, .86),
        text=hsl(h, min(.18, s * .3), .10), muted=hsl(h, min(.10, s * .16), .35), subtle=hsl(h, min(.10, s * .16), .40),
        selected=hsl(h, s * .55, .92), **{'on-accent': '#ffffff'})
    l = .46
    while True:
        acc = hsl(h, s, l)
        if contrast(acc, '#ffffff') >= 4.8 and contrast(acc, t['canvas']) >= 4.5:
            break
        l -= .01
    t['accent'] = acc
    return t


def dark(h, s):
    tint = min(.10, s * .14)
    t = dict(
        canvas=hsl(h, tint, .075), sidebar=hsl(h, tint, .055), surface=hsl(h, tint, .11),
        raised=hsl(h, tint, .155), line=hsl(h, tint, .22),
        text=hsl(h, .08, .94), muted=hsl(h, .07, .72), subtle=hsl(h, .07, .66),
        selected=hsl(h, s * .40, .20))
    l = .66
    while True:
        acc = hsl(h, min(1, s * 1.1), l)
        if contrast(acc, t['raised']) >= 6:
            break
        l += .01
    t['accent'] = acc
    t['on-accent'] = hsl(h, .4, .08)
    return t


def checks(mode, t):
    pairs = [('text', 'canvas', 7), ('text', 'surface', 7), ('muted', 'surface', 4.5), ('muted', 'canvas', 4.5),
             ('subtle', 'surface', 4.5), ('on-accent', 'accent', 4.5), ('text', 'selected', 4.5), ('muted', 'raised', 4.5)]
    for a, b, need in pairs:
        c = contrast(t[a], t[b])
        assert c >= need, f'{mode}: {a}/{b} {c:.2f} < {need}'


def block(sel, t, extra=''):
    body = ';'.join(f'--elio-{k}:{v}' for k, v in t.items())
    return f'{sel}{{{body}{";" + extra if extra else ""}}}'


def build():
    out = [BEGIN, '/* Palette = near-neutral surface tokens + one accent. The logo and swatches use the accent. */']
    sw = []
    for pid, name, h, s, _blobs in PALETTES:
        lt, dk = light(h, s), dark(h, s)
        checks(pid + ' light', lt)
        checks(pid + ' dark', dk)
        out.append(block(f'html[data-elio-palette="{pid}"]', lt))
        out.append(block(f'html[data-elio-palette="{pid}"][data-elio-mode=dark]', dk))
        sw.append(f'[data-elio-swatch="{pid}"]{{--sw-a:{hsl(h, s, .50)}}}')
    out.append('/* swatches in the palette pickers */')
    out.extend(sw)
    out.append(END)
    return '\n'.join(out)


def main():
    for rel in ('core/theme.css',):
        p = ROOT / rel
        text = p.read_text(encoding='utf-8')
        region = build()
        if BEGIN in text:
            text = re.sub(re.escape(BEGIN) + r'.*?' + re.escape(END), lambda m: region, text, flags=re.S)
        else:
            text = text.rstrip('\n') + '\n' + region + '\n'
        p.write_text(text, encoding='utf-8')
        shutil.copy2(p, ROOT / 'elio-Extension' / rel)
    ids = [{'id': p[0], 'name': p[1]} for p in PALETTES]
    print('palettes:', json.dumps(ids))


if __name__ == '__main__':
    main()
