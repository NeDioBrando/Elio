#!/usr/bin/env python3
"""Turn a mesh-stage manifest into the two things a game needs to USE the meshes.

    python mesh_bank.py --manifest work/meshes/manifest.json \\
        --bank src/shared/Config/MeshBank.luau \\
        --install work/meshes/install_templates.lua

THE DEFECT THIS EXISTS FOR (2026-09-28, a real game build, section 3).

An earlier incremental game (2026-09-18) proved the runtime half - a MeshFactory that
clones ReplicatedStorage.MeshTemplates[name], falls back to
CreateMeshPartAsync(meshId), and never throws - but the two files that feed it
were written BY HAND in that project: the MeshBank.luau id table and the
execute_luau snippet that builds the templates. The next build had to rediscover
both from a transcript. This script is the missing generator, so the bank and the
installer always come from the manifest and cannot disagree with it.

Why a template folder at all, and not MeshBank + CreateMeshPartAsync alone:
  * MeshPart.MeshId is not script-writable, so Rojo cannot sync a mesh;
  * CreateMeshPartAsync returns an UNTEXTURED part, and SurfaceAppearance.ColorMap
    is not writable from a game script either;
  * a PLUGIN (execute_luau) may write both. So the installer runs once in Studio,
    builds fully textured templates into ReplicatedStorage.MeshTemplates (outside
    every Rojo-owned subtree, so Rojo never deletes them), and the place is saved.

The installer RETURNS a JSON table {name: {meshId, textureId, size}}; save it and
run fill_meshbank_ids.py --bank ... --ids <that json> so the bank's meshId rows
(rung 2 of the ladder) are real. Pending rows are loud strings on purpose - see
fill_meshbank_ids.py for why an empty id is the dangerous placeholder.

APPROVAL GATE (2026-09-29). Studio caches a FAILED image fetch for
the rest of the session. The Sandwich texture was applied by the installer while
Open Cloud still had it "Reviewing"; once approved it STILL rendered untextured
(grey, or black), and every probe of the image itself said it was fine. Only a
fresh upload under a new id rendered. So by default this script asks Open Cloud
for every image's moderationState and refuses to write the installer while any
is not Approved (--no-approval-check to skip; needs ROBLOX_API_KEY).

Manifest rows need: name, model_id, image_id; optional bounds_studs [x,y,z],
collide (bool). Ids may be bare numbers or rbxassetid:// strings.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from pathlib import Path


def asset_url(v) -> str:
    s = str(v or "").strip()
    if not s:
        return ""
    m = re.search(r"(\d{5,})", s)
    return f"rbxassetid://{m.group(1)}" if m else ""


def load_rows(path: Path) -> list[dict]:
    data = json.loads(path.read_text(encoding="utf-8"))
    rows = data.get("assets", data) if isinstance(data, dict) else data
    out = []
    for r in rows:
        if not r.get("name"):
            continue
        out.append(r)
    return out


def bank_luau(rows: list[dict]) -> str:
    lines = [
        "--!strict",
        "-- MeshBank - GENERATED by roblox-3d-model/scripts/mesh_bank.py from the mesh",
        "-- manifest. Do not hand-edit: re-run the generator, then fill_meshbank_ids.py.",
        "--",
        "-- Three ids per asset: the MODEL Open Cloud returned, the inner MESH Roblox minted",
        "-- on ingest (read in Studio by the installer), and the colour-map IMAGE, which",
        "-- attaches to nothing on its own. MeshFactory clones",
        "-- ReplicatedStorage.MeshTemplates[name] first; meshId is only its fallback.",
        "",
        "export type Entry = {",
        "\tmodelId: string,",
        "\tmeshId: string,",
        "\ttextureId: string,",
        "\tsize: Vector3,",
        "\tcanCollide: boolean,",
        "}",
        "",
        "local MeshBank = {}",
        "",
        "local entries: { [string]: Entry } = {",
    ]
    for r in rows:
        name = r["name"]
        b = r.get("bounds_studs") or [1, 1, 1]
        mesh = asset_url(r.get("mesh_id")) or f"MESHID_PENDING_STUDIO_INSERT::{name}"
        lines += [
            f'\t["{name}"] = {{',
            f'\t\tmodelId = "{asset_url(r.get("model_id"))}",',
            f'\t\tmeshId = "{mesh}",',
            f'\t\ttextureId = "{asset_url(r.get("image_id"))}",',
            f"\t\tsize = Vector3.new({b[0]:.3f}, {b[1]:.3f}, {b[2]:.3f}),",
            f"\t\tcanCollide = {'true' if r.get('collide') else 'false'},",
            "\t},",
        ]
    lines += [
        "}",
        "",
        "MeshBank.entries = entries",
        "",
        "--- The inner mesh id, or nil while it is still pending a Studio insert.",
        "function MeshBank.meshIdFor(name: string): string?",
        "\tlocal e = entries[name]",
        '\tif not e or e.meshId == "" or string.find(e.meshId, "PENDING", 1, true) then',
        "\t\treturn nil",
        "\tend",
        "\treturn e.meshId",
        "end",
        "",
        "return MeshBank",
        "",
    ]
    return "\n".join(lines)


def install_lua(rows: list[dict]) -> str:
    items = []
    for r in rows:
        items.append(
            '\t{name="%s", model="%s", tex="%s", collide=%s},'
            % (r["name"], asset_url(r.get("model_id")), asset_url(r.get("image_id")),
               "true" if r.get("collide") else "false")
        )
    body = "\n".join(items)
    return f"""-- GENERATED by roblox-3d-model/scripts/mesh_bank.py. Run with execute_luau
-- (plugin capability: it writes TextureID on a MeshPart, which a game script cannot).
-- Builds ReplicatedStorage.MeshTemplates and returns JSON {{name: {{meshId, textureId, size}}}}.
local RS = game:GetService("ReplicatedStorage")
local InsertService = game:GetService("InsertService")
local HttpService = game:GetService("HttpService")
local ASSETS = {{
{body}
}}
local folder = RS:FindFirstChild("MeshTemplates")
if not folder then
	folder = Instance.new("Folder")
	folder.Name = "MeshTemplates"
	folder.Parent = RS
end
local out, failed = {{}}, {{}}
for _, a in ASSETS do
	local ok, model = pcall(function() return InsertService:LoadAsset(tonumber(string.match(a.model, "%d+"))) end)
	if not ok then
		ok, model = pcall(function() return game:GetObjects(a.model)[1] end)
	end
	local mp = nil
	if ok and model then
		if model:IsA("MeshPart") then mp = model else mp = model:FindFirstChildWhichIsA("MeshPart", true) end
	end
	if not mp then
		failed[a.name] = tostring(model)
	else
		local old = folder:FindFirstChild(a.name)
		if old then old:Destroy() end
		mp.Parent = nil
		mp.Name = a.name
		if a.tex ~= "" then mp.TextureID = a.tex end
		mp.Anchored = true
		mp.CanCollide = a.collide
		mp.CanTouch = false
		mp.CanQuery = a.collide
		-- plugin-only property: set here on the template, clones inherit it
		pcall(function() mp.CollisionFidelity = Enum.CollisionFidelity.Box end)
		mp.CFrame = CFrame.new()
		mp.Parent = folder
		out[a.name] = {{ meshId = mp.MeshId, textureId = mp.TextureID, size = tostring(mp.Size) }}
	end
	if model and model ~= mp and typeof(model) == "Instance" then model:Destroy() end
end
return HttpService:JSONEncode({{ ok = out, failed = failed }})
"""


def unapproved(rows: list[dict]) -> list[str]:
    import os
    import urllib.request
    key = os.environ.get("ROBLOX_API_KEY")
    if not key:
        return ["(no ROBLOX_API_KEY: cannot check approval; pass --no-approval-check)"]
    out = []
    for r in rows:
        m = re.search(r"(\d{5,})", str(r.get("image_id") or ""))
        if not m:
            continue
        req = urllib.request.Request(f"https://apis.roblox.com/assets/v1/assets/{m.group(1)}",
                                     headers={"x-api-key": key})
        try:
            with urllib.request.urlopen(req, timeout=20) as resp:
                state = json.load(resp).get("moderationResult", {}).get("moderationState")
        except Exception as exc:  # noqa: BLE001
            state = f"error {exc}"
        if state != "Approved":
            out.append(f"{r['name']}={state}")
    return out


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--manifest", required=True)
    ap.add_argument("--bank", required=True, help="MeshBank.luau to write")
    ap.add_argument("--install", required=True, help="installer .lua to write")
    ap.add_argument("--no-approval-check", action="store_true")
    a = ap.parse_args()
    rows = load_rows(Path(a.manifest))
    if not a.no_approval_check:
        pending = unapproved(rows)
        if pending:
            print("NOT APPROVED YET - wait, then re-run (Studio caches a failed fetch for the "
                  "whole session): " + ", ".join(pending), file=sys.stderr)
            return 2
    missing = [r["name"] for r in rows if not asset_url(r.get("model_id"))]
    Path(a.bank).write_text(bank_luau(rows), encoding="utf-8", newline="\n")
    Path(a.install).write_text(install_lua(rows), encoding="utf-8", newline="\n")
    print(f"bank: {len(rows)} entries -> {a.bank}")
    print(f"install: {a.install}")
    if missing:
        print(f"NO MODEL ID (not uploaded): {', '.join(missing)}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
